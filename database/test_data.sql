-- ============================================================
-- 2. 生成房间（1号、2号、3号楼，各6层×20间=120间，共360间）
--    房间号格式: 楼层(2位)+序号(2位)，如 0101~0120, 0201~0220 ...
-- ============================================================
INSERT IGNORE INTO rooms (building_id, room_number, floor, capacity, current_count, status, room_type, window_beds_count, corridor_beds_count, is_active)
SELECT b.id, CONCAT(LPAD(f.floor, 2, '0'), LPAD(rn, 2, '0')), f.floor, 4, 0, 1, '4人间', 2, 2, 1
FROM buildings b
CROSS JOIN (
    SELECT 1 as floor UNION SELECT 2 UNION SELECT 3
    UNION SELECT 4 UNION SELECT 5 UNION SELECT 6
) f
CROSS JOIN (
    SELECT 1 as rn UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5
    UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9 UNION SELECT 10
    UNION SELECT 11 UNION SELECT 12 UNION SELECT 13 UNION SELECT 14 UNION SELECT 15
    UNION SELECT 16 UNION SELECT 17 UNION SELECT 18 UNION SELECT 19 UNION SELECT 20
) rn
WHERE b.name IN ('1号楼', '2号楼', '3号楼')
ORDER BY b.id, f.floor, rn.rn;

-- ============================================================
-- 3. 生成床位（每间房4张：A靠窗、B靠窗、C靠走廊、D靠走廊）
--    共计 360间×4 = 1440张床位
-- ============================================================
INSERT IGNORE INTO bed (room_id, bed_number, bed_type, is_occupied)
SELECT r.id, b.bed_number, b.bed_type, 0
FROM rooms r
CROSS JOIN (
    SELECT 'A' as bed_number, 'window' as bed_type
    UNION ALL SELECT 'B', 'window'
    UNION ALL SELECT 'C', 'corridor'
    UNION ALL SELECT 'D', 'corridor'
) b
WHERE r.building_id IN (SELECT id FROM buildings WHERE name IN ('1号楼', '2号楼', '3号楼'))
ORDER BY r.id, b.bed_number;

